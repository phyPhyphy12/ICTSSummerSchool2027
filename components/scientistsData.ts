export const getIndianScientistRatio = (): { total: number; indian: number; percentage: number } => {
  const total = SCIENTISTS.length;
  const indian = SCIENTISTS.filter((s) => s.isIndian).length;
  const percentage = Math.round((indian / total) * 100);
  return { total, indian, percentage };
};
